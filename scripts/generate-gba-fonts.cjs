/** Extract glyph IDs and advances from the original C data; PNGs remain the atlas source. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, 'public/pokeemerald', file), 'utf8');
const charmap = {};
for (const match of read('charmap.txt').matchAll(/^'(.+)'\s*=\s*([A-F0-9]{2})\s*$/gm)) {
  if ([...match[1]].length === 1) charmap[match[1]] = parseInt(match[2], 16);
}
// The level ligature is an extra symbol (F9 05), indexing the second glyph bank.
charmap['⒧'] = 0x105;
const fonts = read('src/fonts.c');
const widths = {};
for (const name of ['Small', 'Normal', 'Narrow']) {
  const body = fonts.match(new RegExp(`gFont${name}LatinGlyphWidths\\[\\] = \\{([\\s\\S]*?)\\};`))[1];
  widths[name.toLowerCase()] = [...body.matchAll(/\d+/g)].map((match) => Number(match[0]));
  if (widths[name.toLowerCase()].length !== 512) throw new Error(`Unexpected ${name} font length`);
}
const output = `// Generated by scripts/generate-gba-fonts.cjs. Do not edit.\n// Sources: public/pokeemerald/charmap.txt and public/pokeemerald/src/fonts.c\nexport const GBA_GLYPHS: Readonly<Record<string, number>> = ${JSON.stringify(charmap)};\nexport const GBA_FONT_WIDTHS = ${JSON.stringify(widths)} as const;\n`;
fs.writeFileSync(path.join(root, 'src/data/gbaFonts.gen.ts'), output);
